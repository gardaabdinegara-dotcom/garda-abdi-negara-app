export type IntiTable = keyof typeof INTI;
export type KeuanganTable = keyof typeof KEUANGAN;

export const SCHEMA: Record<SpreadsheetKey, Record<string, TableDef>> = { inti: INTI, keuangan: KEUANGAN };
export const OPERATION_TABLE: Record<SpreadsheetKey, string> = { inti: "Operasi", keuangan: "Operasi_Keuangan" };
export const SCHEMA_VERSION = "1";

export function tableDef(sheet: SpreadsheetKey, table: string): TableDef {
  const found = SCHEMA[sheet][table];
  if (!found) throw new Error(`Tab ${table} tidak dikenal pada spreadsheet ${sheet}.`);
  return found;
}

